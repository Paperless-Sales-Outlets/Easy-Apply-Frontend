/**
 * Returns the 5-digit Sri Lankan postal code for a given city and/or district.
 * Uses exact match, alias normalization, and substring searching.
 *
 * @param {string} city - e.g. "DICKOYA", "Colombo 03", "Hatton"
 * @param {string} [district] - Optional district hint (e.g. "Nuwara Eliya")
 * @returns {string} 5-digit postal code or empty string
 */
export function getPostalCodeByCity(city = '', district = '') {
  if (!city && !district) return '';

  const cleanCity = (city || '')
    .toUpperCase()
    .replace(/[\.,\-_#\(\)]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();

  // 1. Direct match (e.g. "DICKOYA", "COLOMBO 03", "KANDY")
  if (cleanCity && SRI_LANKA_POSTAL_CODES[cleanCity]) {
    return SRI_LANKA_POSTAL_CODES[cleanCity];
  }

  // 2. Normalize numbered areas (e.g. "COLOMBO 3" -> "COLOMBO 03")
  const colomboMatch = cleanCity.match(/COLOMBO\s*0?([1-9]|1[0-5])\b/);
  if (colomboMatch) {
    const num = colomboMatch[1].padStart(2, '0');
    const key = `COLOMBO ${num}`;
    if (SRI_LANKA_POSTAL_CODES[key]) return SRI_LANKA_POSTAL_CODES[key];
  }

  // 3. Substring / word search in key dictionary
  if (cleanCity.length >= 3) {
    for (const [town, pCode] of Object.entries(SRI_LANKA_POSTAL_CODES)) {
      if (cleanCity === town || cleanCity.includes(town) || town.includes(cleanCity)) {
        return pCode;
      }
    }
  }

  // 4. Fallback to District Capital postal code if known
  if (district && DISTRICT_CAPITAL_POSTAL_CODES[district]) {
    return DISTRICT_CAPITAL_POSTAL_CODES[district];
  }

  return '';
}
